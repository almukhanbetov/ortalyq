package workshop

import "strings"

// Action — действие над выделенным фрагментом.
type Action struct {
	ID    string `json:"id"`
	Label string `json:"label"`
	Hint  string `json:"hint"`
	// Guidance — что именно должна сделать модель (часть системных инструкций).
	Guidance string `json:"-"`
	// Verdict — действие проверяет ответ: модель обязана выбрать вердикт (верно / допустимо / ошибка / не хватает условия).
	Verdict bool `json:"verdict"`
}

// Mode — предметный режим мастерской.
type Mode struct {
	ID          string   `json:"id"`
	Label       string   `json:"label"`
	Description string   `json:"description"`
	Actions     []Action `json:"actions"`
	// Guidance — общие указания режима для всех действий и домашнего задания.
	Guidance string `json:"-"`
	// HomeworkGuidance — дополнительные указания для домашнего задания.
	HomeworkGuidance string `json:"-"`
	// SuggestFor — фрагменты (в нижнем регистре) названия предмета, при которых интерфейс ПРЕДЛАГАЕТ этот режим.
	// Это только подсказка преподавателю: режим включает преподаватель, функциональность от названия не зависит.
	SuggestFor []string `json:"-"`
}

// Level — сложность, выбранная преподавателем.
type Level struct {
	ID       string `json:"id"`
	Label    string `json:"label"`
	Guidance string `json:"-"`
}

