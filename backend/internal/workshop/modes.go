// Modes — доступные режимы. Здесь только работающие режимы: неготовые не добавляются.
func Modes() []Mode { return modes }

func Levels() []Level { return levels }

func ModeByID(id string) (*Mode, bool) {
	for i := range modes {
		if modes[i].ID == id {
			return &modes[i], true
		}
	}
	return nil, false
}

func (m *Mode) Action(id string) (*Action, bool) {
	for i := range m.Actions {
		if m.Actions[i].ID == id {
			return &m.Actions[i], true
		}
	}
	return nil, false
}

func LevelByID(id string) (*Level, bool) {
	for i := range levels {
		if levels[i].ID == id {
			return &levels[i], true
		}
	}
	return nil, false
}

// SuggestMode — режим, который интерфейс может предложить преподавателю по названию предмета; "" — нет предложения.
func SuggestMode(subject string) string {
	s := strings.ToLower(subject)
	for _, m := range modes {
		for _, k := range m.SuggestFor {
			if strings.Contains(s, k) {
				return m.ID
			}
		}
	}
	return ""
}
