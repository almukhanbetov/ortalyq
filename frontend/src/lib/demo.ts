const minutesWord = (n: number) => {
  const d = n % 10, h = n % 100;
  return d === 1 && h !== 11 ? "минуту" : d >= 2 && d <= 4 && (h < 12 || h > 14) ? "минуты" : "минут";
};

/** Предупреждение перед запуском: содержимое демонстрации хранится только в памяти сервиса. */
export const demoTempNotice = (minutes: number) =>
  `Демонстрация длится ${minutes} ${minutesWord(minutes)}. Материалы временные и могут быть потеряны при перезапуске сервиса`;

/** Узкий экран (телефон): подсказки в классе изначально свёрнуты, чтобы не закрывать доску. */
export const isNarrowScreen = () => typeof window !== "undefined" && window.matchMedia("(max-width: 767px)").matches;
